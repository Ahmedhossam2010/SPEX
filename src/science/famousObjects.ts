export function getFamousObjectById(id: string): FamousObject | undefined {
  return FAMOUS_OBJECTS_CATALOG.find((obj) => obj.id.toLowerCase() === id.toLowerCase());
}

export function searchFamousObjects(query: string, category: FamousCategory = 'All'): FamousObject[] {
  const q = query.toLowerCase().trim();
  let list = FAMOUS_OBJECTS_CATALOG;
  if (category && category !== 'All') {
    list = list.filter((obj) => obj.categories.includes(category));
  }
  if (!q) return list;
  return list.filter(
    (obj) =>
      obj.name.toLowerCase().includes(q) ||
      obj.nameAr.includes(q) ||
      obj.designation.toLowerCase().includes(q) ||
      obj.constellation.toLowerCase().includes(q) ||
      obj.constellationAr.includes(q) ||
      obj.classification.toLowerCase().includes(q)
  );
}
